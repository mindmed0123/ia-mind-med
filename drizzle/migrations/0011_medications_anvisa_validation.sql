DROP FUNCTION IF EXISTS public.search_medications(text, text);

CREATE FUNCTION public.search_medications(q text DEFAULT NULL, cid text DEFAULT NULL)
RETURNS TABLE(
  id uuid, nome_comercial text, principio_ativo text, laboratorio text, apresentacao text,
  concentracao text, forma_farmaceutica text, via_administracao text, classe_terapeutica text,
  registro_anvisa text, tarja text, tipo_receita text, posologia_referencia text,
  indicacoes text, contraindicacoes text, cid10_relacionados text[], is_parceiro boolean,
  parceiro_nome text, recomendado_cid boolean, anvisa_situacao text, anvisa_titular text,
  anvisa_verificado_em timestamptz
)
LANGUAGE sql
STABLE SECURITY DEFINER
SET search_path TO 'public'
AS $function$
  WITH qn AS (
    SELECT unaccent(lower(btrim(coalesce(q, '')))) AS qt,
           -- O CID vem como "G44.2" ou "G44.2 - Cefaleia tensional": usa só o código.
           upper(substring(coalesce(cid, '') from '^\s*([A-Za-z][0-9]{2}(?:\.[0-9A-Za-z]+)?)')) AS code
  ), base AS (
    SELECT m.*, qn.qt,
      (qn.code IS NOT NULL AND EXISTS (
         SELECT 1 FROM unnest(coalesce(m.cid10_relacionados, ARRAY[]::text[])) c
         WHERE upper(c) = qn.code OR left(upper(c), 3) = left(qn.code, 3)
      )) AS rec
    FROM public.medications m, qn
    WHERE m.ativo = true
      AND (
        qn.qt = ''
        OR to_tsvector('portuguese', unaccent(coalesce(m.nome_comercial,'') || ' ' || coalesce(m.principio_ativo,'') || ' ' || coalesce(m.classe_terapeutica,'')))
           @@ plainto_tsquery('portuguese', qn.qt)
        OR unaccent(lower(m.nome_comercial))  LIKE '%' || qn.qt || '%'
        OR unaccent(lower(m.principio_ativo)) LIKE '%' || qn.qt || '%'
        OR similarity(unaccent(lower(m.nome_comercial)),  qn.qt) > 0.3
        OR similarity(unaccent(lower(m.principio_ativo)), qn.qt) > 0.3
      )
  )
  SELECT b.id, b.nome_comercial, b.principio_ativo, b.laboratorio, b.apresentacao,
    b.concentracao, b.forma_farmaceutica, b.via_administracao, b.classe_terapeutica,
    b.registro_anvisa, b.tarja, b.tipo_receita, b.posologia_referencia,
    b.indicacoes, b.contraindicacoes, b.cid10_relacionados,
    b.is_parceiro, b.parceiro_nome, b.rec, b.anvisa_situacao, b.anvisa_titular,
    b.anvisa_verificado_em
  FROM base b
  ORDER BY
    CASE WHEN b.qt <> '' AND unaccent(lower(b.nome_comercial)) LIKE b.qt || '%' THEN 0 ELSE 1 END,
    b.rec DESC,
    b.pinned DESC,
    b.is_parceiro DESC,
    GREATEST(similarity(unaccent(lower(b.nome_comercial)), b.qt), similarity(unaccent(lower(b.principio_ativo)), b.qt)) DESC,
    b.destaque_ordem ASC,
    b.nome_comercial ASC
  LIMIT 60;
$function$;

REVOKE ALL ON FUNCTION public.search_medications(text, text) FROM PUBLIC, anon;
